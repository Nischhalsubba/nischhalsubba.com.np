function setText(element, text) {
  if (!element || !text) return;
  element.textContent = text;
}

function createEl(tag, className, text) {
  const el = document.createElement(tag);
  if (className) el.className = className;
  if (text) el.textContent = text;
  return el;
}

function buildSnapshotGrid(project) {
  const grid = createEl('div', 'snapshot-grid nrs-case-study-snapshot');
  Object.entries(project.snapshot).forEach(([label, value]) => {
    const item = createEl('div');
    item.append(createEl('h5', null, label), createEl('p', null, value));
    grid.appendChild(item);
  });
  return grid;
}

function buildDecisionCards(project) {
  const grid = createEl('div', 'journey-grid nrs-case-study-decisions');
  project.decisions.forEach(([decision, why, tradeoff, result]) => {
    const card = createEl('article', 'journey-card');
    card.append(
      createEl('span', 'eyebrow', 'Decision'),
      createEl('h3', null, decision),
      createEl('p', null, `Why: ${why}`),
      createEl('p', null, `Constraint: ${tradeoff}`),
      createEl('p', null, `Result: ${result}`),
    );
    grid.appendChild(card);
  });
  return grid;
}

function buildList(items) {
  const list = createEl('ul', 'case-list');
  items.forEach((item) => list.appendChild(createEl('li', null, item)));
  return list;
}

function renderAdditionalCaseStudy(project) {
  const main = document.querySelector('main.container');
  const hero = main?.querySelector('.hero-section');
  if (!main || !hero || main.dataset.additionalCaseStudyRendered) return;

  main.dataset.additionalCaseStudyRendered = 'true';
  setText(hero.querySelector('.hero-title'), project.title);
  setText(hero.querySelector('.body-large, .section-lead'), project.summary);

  const image = main.querySelector('.case-hero-img-container');
  const closing = Array.from(main.querySelectorAll('.section-container')).slice(-1)[0];
  const content = document.createDocumentFragment();

  const sections = [
    ['Snapshot', 'Project snapshot', buildSnapshotGrid(project)],
    ['Context', 'Project context', project.context],
    ['Role', 'My role and scope', project.role],
    ['Problem', 'What needed to be made clearer', project.problem],
    ['Design decisions', 'Key decisions', buildDecisionCards(project)],
    ['Evidence', 'Evidence to review', buildList(project.evidence)],
    ['Impact', 'Honest impact', project.impact],
    ['Reflection', 'What this project shows', project.reflection],
  ];

  sections.forEach(([label, title, body]) => {
    const section = createEl('section', 'section-container reveal-on-scroll');
    section.append(createEl('div', 'case-label', label), createEl('h2', 'section-title', title));
    if (typeof body === 'string') section.appendChild(createEl('p', 'body-large', body));
    else section.appendChild(body);
    content.appendChild(section);
  });

  Array.from(main.children).forEach((child) => {
    if (child === hero || child === image || child === closing) return;
    child.remove();
  });

  if (image) image.after(content);
  else hero.after(content);
}

export function addRemainingCaseStudyCoverage() {
  const project = ADDITIONAL_PROJECTS[window.location.pathname];
  if (project) renderAdditionalCaseStudy(project);
}
