/**
 * @fileoverview scripts/seo-discovery-lib.cjs
 * Purpose: Provide deterministic helpers for canonical route loading, sitemap generation, robots output, and production redirect generation.
 * Responsibilities:
 * - Read the canonical route manifest used by search and redirect tooling.
 * - Convert HTML source filenames into clean public routes.
 * - Generate standards-based sitemap and robots content.
 * - Generate matching static and Worker redirect definitions from one manifest.
 * Execution context: Node.js helper module imported by search-discovery generation and audit scripts.
 * Connected files:
 * - config/canonical-routes.json
 * - scripts/generate-seo-discovery.cjs
 * - scripts/audit-seo-discovery.cjs
 * - src/generated/legacy-redirects.js
 * - public/_redirects
 * Maintenance: Keep this module small and deterministic. Route policy belongs in the manifest; this file should translate that policy into deployable artifacts rather than invent additional route rules.
 */
const fs = require('node:fs');
const path = require('node:path');

const SITE = 'https://nischhalsubba.com.np';

/**
 * Function contract: loadManifest
 * Purpose: Read and parse the repository's canonical route manifest.
 * Inputs: `root` - Absolute repository root path.
 * Side effects: Reads `config/canonical-routes.json` from disk.
 * Returns: Parsed canonical route manifest object.
 */
function loadManifest(root) {
  return JSON.parse(fs.readFileSync(path.join(root, 'config', 'canonical-routes.json'), 'utf8'));
}

/**
 * Function contract: routeForFile
 * Purpose: Convert a canonical HTML output filename into the corresponding clean public route.
 * Inputs: `file` - Repository-style HTML path from the canonical route manifest.
 * Side effects: None.
 * Returns: Public route beginning with `/` and without a trailing `.html` extension.
 */
function routeForFile(file) {
  if (file === 'index.html') return '/';
  if (file === 'blog/index.html') return '/blog/';
  return `/${file.replace(/\\/g, '/').replace(/\.html$/i, '')}`;
}

/**
 * Function contract: xmlEscape
 * Purpose: Escape text before placing it inside XML element content.
 * Inputs: `value` - String to escape.
 * Side effects: None.
 * Returns: XML-safe string.
 */
function xmlEscape(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/**
 * Function contract: buildSitemap
 * Purpose: Generate the XML sitemap from the canonical HTML route list.
 * Inputs: `manifest` - Parsed canonical route manifest.
 * Side effects: None.
 * Returns: Complete UTF-8 sitemap XML text ending with a newline.
 */
function buildSitemap(manifest) {
  const entries = manifest.html
    .map(
      /** Callback contract: Convert one canonical HTML file into a sitemap `<url>` entry. Inputs: `file` Side effects: None. Returns: XML string for the route. */
      (file) => `  <url><loc>${xmlEscape(`${SITE}${routeForFile(file)}`)}</loc></url>`,
    )
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

/**
 * Function contract: buildRobots
 * Purpose: Generate the repository's standards-based public `robots.txt` contents.
 * Inputs: None.
 * Side effects: None.
 * Returns: Complete robots text allowing public crawling and linking the canonical sitemap.
 */
function buildRobots() {
  return `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`;
}

/**
 * Function contract: buildRedirectFile
 * Purpose: Generate Cloudflare-compatible static redirect rules from the canonical redirect manifest.
 * Inputs: `manifest` - Parsed canonical route manifest containing the `redirects` object.
 * Side effects: None.
 * Returns: Complete `_redirects` file contents.
 */
function buildRedirectFile(manifest) {
  const lines = [
    '# Generated from config/canonical-routes.json by scripts/generate-seo-discovery.cjs.',
    '# Do not edit this file directly. Update the manifest and regenerate instead.',
    '',
  ];

  for (const [from, to] of Object.entries(manifest.redirects)) {
    lines.push(`${from}  ${to}  301`);
  }

  return `${lines.join('\n')}\n`;
}

/**
 * Function contract: buildRedirectModule
 * Purpose: Generate the JavaScript redirect map consumed by the Cloudflare Worker runtime.
 * Inputs: `manifest` - Parsed canonical route manifest containing the `redirects` object.
 * Side effects: None.
 * Returns: JavaScript module text exporting the generated legacy redirect map.
 */
function buildRedirectModule(manifest) {
  const entries = Object.entries(manifest.redirects)
    .map(
      /** Callback contract: Serialize one redirect pair as a JavaScript Map entry. Inputs: `[from, to]` Side effects: None. Returns: One formatted map-entry line. */
      ([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`,
    )
    .join('\n');

  return `// Generated from config/canonical-routes.json. Do not edit by hand.\nexport const LEGACY_REDIRECTS = new Map([\n${entries}\n]);\n`;
}

module.exports = {
  SITE,
  loadManifest,
  routeForFile,
  buildSitemap,
  buildRobots,
  buildRedirectFile,
  buildRedirectModule,
};
